def eff(**raw):
    return pol.effective({'version': 2, **raw})


class Globs(unittest.TestCase):
    def test_glob_semantics(self):
        cases = [('**/tests/**', 'tests/a.py', True), ('**/tests/**', 'pkg/tests/x/a.py', True),
                 ('**/*.test.*', 'a.test.ts', True), ('src/*.py', 'src/a/b.py', False),
                 ('**/*.{js,ts}', 'x/y.ts', True), ('docs/**', 'docs', False), ('a?.py', 'ab.py', True),
                 ('src/{*.ts,*.js}', 'src/a.js', True), ('src/{*.ts,*.js}', 'src/a.py', False),
                 ('{app,lib}/**/*.go', 'lib/x/y.go', True)]
        for pattern, path, expected in cases:
            with self.subTest(pattern=pattern, path=path):
                self.assertEqual(pol.glob_match(path, pattern), expected)

    def test_exception_wildcards_treat_brackets_literally(self):
        self.assertTrue(pol.wildcard_match('tests/test_a.py::test_x[1-2]', 'tests/test_a.py::*'))
        self.assertTrue(pol.wildcard_match('t::case[a]', 't::case[a]'))
        self.assertFalse(pol.wildcard_match('t::casea', 't::case[a]'))


class Kinds(unittest.TestCase):
    def test_default_kinds(self):
        p = eff()
        cases = {'src/app.py': 'logic', 'src/App.tsx': 'ui', 'tests/test_app.py': 'test', 'pkg/foo_test.go': 'test',
                 'api/x.pb.go': 'generated', 'vendor/lib/a.go': 'vendor', 'db/migrations/0001_init.py': 'migration',
                 'src/types/user.ts': 'model', 'scripts/release.sh': 'script', 'app/models/user.rb': 'model',
                 'src/main/java/AppTest.java': 'test', 'lib/widget.g.dart': 'generated'}
        for path, kind in cases.items():
            with self.subTest(path):
                self.assertEqual(pol.classify(p, path), kind)

    def test_generated_header_only_reclassifies_logic(self):
        p = eff()
        header = '// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n'
        self.assertEqual(pol.classify(p, 'src/x.go', header), 'generated')
        self.assertEqual(pol.classify(p, 'tests/x_test.go', header), 'test')
        self.assertEqual(pol.classify(p, 'src/x.go', 'package x\n// handles auto-generated ids\n'), 'logic')

    def test_project_globs_win_over_defaults(self):
        p = eff(paths={'logic': ['src/components/**/*.tsx'], 'generated': ['src/api/**']})
        self.assertEqual(pol.classify(p, 'src/components/form/Form.tsx'), 'logic')
        self.assertEqual(pol.classify(p, 'src/api/client.ts'), 'generated')

    def test_roles(self):
        p = eff(roles={'public-api': ['src/index.ts']})
        self.assertIn('security', pol.roles_of(p, 'src/auth/session.ts'))
        self.assertIn('security', pol.roles_of(p, 'lib/password_reset.py'))
        self.assertNotIn('security', pol.roles_of(p, 'src/authors/list.py'))
        self.assertIn('public-api', pol.roles_of(p, 'src/index.ts'))
        self.assertIn('migration', pol.roles_of(p, 'db/migrations/1.sql'))
        self.assertEqual(pol.roles_of(p, 'tools/guard/guard.py'), {'guard'} | pol.roles_of(p, 'tools/guard/guard.py'))
        self.assertTrue({'deps', 'test-config'} <= pol.roles_of(p, 'package.json'))


class Thresholds(unittest.TestCase):
    def test_lookup_order(self):
        spec = eff(thresholds={'fn-complexity': {'limit': {'logic.python': 12, 'ui': None}}})['thresholds']['fn-complexity']
        self.assertEqual(pol.limit_for(spec, 'logic', 'python'), 12)
        self.assertEqual(pol.limit_for(spec, 'logic', 'go'), 25)
        self.assertEqual(pol.limit_for(spec, 'logic', 'java'), 20)
        self.assertIsNone(pol.limit_for(spec, 'ui', 'typescript'))
        self.assertIsNone(pol.limit_for(spec, 'test', 'python'))

    def test_guard_override(self):
        p = eff()
        spec = pol.threshold_spec(p, 'fn-complexity', {'thresholds': {'fn-complexity': {'limit': {'logic': 30}}}})
        self.assertEqual(pol.limit_for(spec, 'logic', 'python'), 30)
        self.assertEqual(pol.limit_for(spec, 'ui', 'python'), 25)


