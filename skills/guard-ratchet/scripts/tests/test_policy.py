class Loosening(unittest.TestCase):
    GUARD = {'name': 'lint', 'run': 'lint {root}', 'parse': 'sarif', 'tier': 'fast'}

    def keys(self, base, cur):
        return [k for k, _ in pol.loosenings(eff(**base), eff(**cur))]

    def test_detects_each_kind_of_loosening(self):
        g = self.GUARD
        cases = {
            'limit raised': ({}, {'thresholds': {'fn-complexity': {'limit': {'logic': 30}}}},
                             'thresholds.fn-complexity.limit.logic'),
            'limit disabled for one language': ({}, {'thresholds': {'fn-complexity': {'limit': {'logic.python': None}}}},
                                                'thresholds.fn-complexity.limit.logic.python'),
            'mode weakened': ({}, {'thresholds': {'file-size': {'mode': 'advisory'}}}, 'thresholds.file-size.mode'),
            'growth widened': ({}, {'thresholds': {'file-size': {'growth': {'pct': 50}}}},
                               'thresholds.file-size.growth.pct'),
            'guard removed': ({'guards': [g]}, {'guards': []}, 'guards.lint'),
            'tier raised': ({'guards': [g]}, {'guards': [{**g, 'tier': 'standard'}]}, 'guards.lint.tier'),
            'when added': ({'guards': [g]}, {'guards': [{**g, 'when': ['ci']}]}, 'guards.lint.when'),
            'made optional': ({'guards': [g]}, {'guards': [{**g, 'required': False}]}, 'guards.lint.required'),
            'command changed': ({'guards': [g]}, {'guards': [{**g, 'run': 'lint --exclude src {root}'}]},
                                'guards.lint.run'),
            'rule mode lowered': ({'guards': [{**g, 'modes': {'E1': 'hard'}}]}, {'guards': [g]}, 'guards.lint.modes.E1'),
            'coverage min lowered': ({'guards': [{'name': 'cov', 'builtin': 'diff-coverage', 'input': 'x', 'min': {'logic': 80}}]},
                                     {'guards': [{'name': 'cov', 'builtin': 'diff-coverage', 'input': 'x', 'min': {'logic': 60}}]},
                                     'guards.cov.min.logic'),
            'rule mode added': ({'guards': [g]}, {'guards': [{**g, 'modes': {'E1': 'off'}}]}, 'guards.lint.modes.E1'),
            'coverage min added below the default': (
                {'guards': [{'name': 'cov', 'builtin': 'diff-coverage', 'input': 'x'}]},
                {'guards': [{'name': 'cov', 'builtin': 'diff-coverage', 'input': 'x', 'min': {'logic': 0}}]},
                'guards.cov.min.logic'),
            'mutation score added below the default': (
                {'guards': [{'name': 'mut', 'builtin': 'mutation', 'input': 'x'}]},
                {'guards': [{'name': 'mut', 'builtin': 'mutation', 'input': 'x', 'min_score': 1}]},
                'guards.mut.min_score'),
            'untested-lines threshold raised': (
                {'guards': [{'name': 'tc', 'builtin': 'test-changes'}]},
                {'guards': [{'name': 'tc', 'builtin': 'test-changes', 'min': {'untested_lines': 999}}]},
                'guards.tc.min.untested_lines'),
            'config file dropped': ({'guards': [{**g, 'config_files': ['ruff.toml', 'setup.cfg']}]},
                                    {'guards': [{**g, 'config_files': ['**/ruff.toml']}]}, 'guards.lint.config_files'),
            'built-in extension remapped': ({}, {'languages': {'.py': 'go'}}, 'languages..py'),
            'exclude added': ({}, {'exclude': ['legacy/**']}, 'exclude'),
            'test glob added': ({}, {'paths': {'test': ['src/**']}}, 'paths.test'),
            'role shrunk': ({'roles': {'public-api': ['src/index.ts']}}, {}, 'roles.public-api'),
            'security pattern': ({}, {'security_pattern': 'nothing'}, 'security_pattern'),
            'strict lines raised': ({}, {'risk': {'strict_changed_lines': 5000}}, 'risk.strict_changed_lines'),
            'protected removed': ({'protected': ['docs/**']}, {}, 'protected'),
            'base changed': ({}, {'base': 'origin/dev'}, 'base'),
            'scope tolerance': ({}, {'scope_tolerance': 0.5}, 'scope_tolerance'),
        }
        for name, (base, cur, key) in cases.items():
            with self.subTest(name):
                self.assertIn(key, self.keys(base, cur))

    def test_tightening_and_non_semantic_edits_are_not_loosening(self):
        g = self.GUARD
        cases = [({}, {'thresholds': {'fn-complexity': {'limit': {'logic': 10, 'test': 30}}}}),
                 ({'guards': [{**g, 'tier': 'standard'}]}, {'guards': [{**g, 'tier': 'fast'}]}),
                 ({'guards': [{**g, 'when': ['ci']}]}, {'guards': [g]}),
                 ({'guards': [g]}, {'guards': [{**g, 'note': 'why', 'timeout': 99}]}),
                 ({}, {'exclude': [], 'roles': {'security': ['src/payments/**']}}),
                 ({'paths': {'generated': ['src/gen/**']}}, {}),
                 ({}, {'paths': {'logic': ['src/components/**']}}),
                 ({'guards': [g]}, {'guards': [{**g, 'modes': {'E1': 'hard'}}]}),
                 ({'guards': [{**g, 'config_files': ['ruff.toml']}]},
                  {'guards': [{**g, 'config_files': ['**/ruff.toml', '**/pyproject.toml']}]}),
                 ({'guards': [{'name': 'cov', 'builtin': 'diff-coverage', 'input': 'x'}]},
                  {'guards': [{'name': 'cov', 'builtin': 'diff-coverage', 'input': 'x', 'min': {'logic': 90}}]})]
        for base, cur in cases:
            with self.subTest(base=base, cur=cur):
                self.assertEqual(self.keys(base, cur), [])

    @unittest.skipIf(sys.version_info < (3, 11), 'TOML manifests need Python 3.11+ (tomllib)')
    def test_dependency_edits_in_a_manifest_are_not_tool_config_changes(self):
        base = b'[project]\nname = "x"\nversion = "1"\ndependencies = ["a"]\n[tool.ruff]\nline-length = 100\n'
        bump = base.replace(b'"1"', b'"2"').replace(b'["a"]', b'["a", "b"]')
        rule = base.replace(b'100', b'200')
        digest = lambda data: pol._config_bytes('sub/pyproject.toml', data)
        self.assertEqual(digest(base), digest(bump))
        self.assertNotEqual(digest(base), digest(rule))
        self.assertEqual(pol._config_bytes('pyproject.toml', b'not toml ['), b'not toml [')

    def test_extra_protected_paths_cannot_drop_the_defaults(self):
        protected = eff(protected=['docs/x'])['protected']
        self.assertIn('docs/x', protected)
        self.assertTrue(set(pol.DEFAULTS['protected']) <= set(protected))

    def test_fingerprint_ignores_non_semantic_fields(self):
        p = eff()
        a = pol.fingerprint(p, {**self.GUARD, 'note': 'x', 'timeout': 5}, {})
        self.assertEqual(a, pol.fingerprint(p, self.GUARD, {}))
        self.assertNotEqual(a, pol.fingerprint(p, {**self.GUARD, 'run': 'other'}, {}))
        self.assertNotEqual(a, pol.fingerprint(p, self.GUARD, {'ruff.toml': 'abc'}))
        tight = eff(thresholds={'fn-complexity': {'limit': {'logic': 10}}})
        self.assertEqual(pol.fingerprint(p, self.GUARD, {}), pol.fingerprint(tight, self.GUARD, {}))
        self.assertNotEqual(pol.fingerprint(p, self.GUARD, {}, ['fn-complexity']),
                            pol.fingerprint(tight, self.GUARD, {}, ['fn-complexity']))


class Exceptions(unittest.TestCase):
    TODAY = dt.date(2026, 6, 1)

    def entry(self, **kw):
        return {'guard': 'g', 'rule': 'r', 'key': 'k', 'reason': 'mirrors the server implementation',
                'approved_by': 'lead', **kw}

    def test_validation(self):
        bad = [self.entry(reason=''), self.entry(reason='ok'), self.entry(approved_by=''), self.entry(extra=1),
               self.entry(max='3'), self.entry(expires='June'), self.entry(expires='2026-05-31'),
               self.entry(key='*'), self.entry(rule='*', key='*'), self.entry(guard='policy', key='thresholds.*'),
               self.entry(key='**'), self.entry(key='*.py'), self.entry(rule='*', key='*/*'),
               self.entry(rule='rule-change', key='**'),
               self.entry(guard='protected', key='*/guard.py'), self.entry(guard='protected', key='tools/*/x')]
        for entry in bad:
            with self.subTest(entry=entry):
                e = exc.Exceptions([entry], self.TODAY)
                self.assertEqual(len(e.problems), 1)
                self.assertFalse(e.problems[0].exceptable)
                self.assertIsNone(e.match('g', 'r', 'k'))

    def test_matching(self):
        e = exc.Exceptions([self.entry(rule='*', key='src/legacy/*', max=40), self.entry(expires='2026-06-01')],
                           self.TODAY)
        self.assertEqual(e.problems, [])
        self.assertIsNotNone(e.match('g', 'fn-complexity', 'src/legacy/a.py#f', 35))
        self.assertIsNone(e.match('g', 'fn-complexity', 'src/legacy/a.py#f', 41))
        self.assertIsNone(e.match('other', 'r', 'src/legacy/x'))
        self.assertIsNotNone(e.match('g', 'r', 'k'))
        self.assertEqual(e.unused(), [])
        upgrade = exc.Exceptions([self.entry(rule='rule-change', key='*'),
                                  self.entry(guard='protected', rule='changed', key='tools/guard/*')], self.TODAY)
        self.assertEqual(upgrade.problems, [])

    def test_add_validates_and_appends(self):
        from helpers import Repo
        repo = Repo()
        self.addCleanup(repo.cleanup)
        with self.assertRaises(GuardError):
            exc.add(repo.root, self.entry(reason='x'))
        exc.add(repo.root, self.entry())
        exc.add(repo.root, self.entry(key='k2'))
        doc = json.loads(repo.read('guards/exceptions.json'))
        self.assertEqual([e['key'] for e in doc['exceptions']], ['k', 'k2'])


