# ─── globs ───────────────────────────────────────────────────────────────────
@lru_cache(maxsize=4096)
def _glob_re(pattern: str) -> re.Pattern:
    out, i = [], 0
    while i < len(pattern):
        c = pattern[i]
        if pattern.startswith('**/', i):
            out.append('(?:.*/)?')
            i += 3
        elif pattern.startswith('**', i):
            out.append('.*')
            i += 2
        elif c == '*':
            out.append('[^/]*')
            i += 1
        elif c == '?':
            out.append('[^/]')
            i += 1
        elif c == '{' and '}' in pattern[i:]:
            end = pattern.index('}', i)
            # Alternatives are globs themselves: {*.ts,*.tsx} (no nested braces).
            out.append('(?:' + '|'.join(_glob_re(p).pattern[1:-1] for p in pattern[i + 1:end].split(',')) + ')')
            i = end + 1
        else:
            out.append(re.escape(c))
            i += 1
    return re.compile('^' + ''.join(out) + '$')


def glob_match(path: str, pattern: str) -> bool:
    return bool(_glob_re(pattern).match(path))


def any_match(path: str, patterns) -> bool:
    return any(glob_match(path, p) for p in patterns or ())


def wildcard_match(value: str, pattern: str) -> bool:
    """Exception rule/key matching: only * is a wildcard (test ids often contain [ and ])."""
    regex = '^' + '.*'.join(re.escape(part) for part in pattern.split('*')) + '$'
    return re.match(regex, value, re.DOTALL) is not None


# ─── loading ─────────────────────────────────────────────────────────────────
def _merge(base: dict, override: dict) -> dict:
    out = copy.deepcopy(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = _merge(out[key], value)
        else:
            out[key] = copy.deepcopy(value)
    return out


def effective(raw: dict) -> dict:
    """Policy file + defaults = the policy in force. Threshold limits merge per key; null disables."""
    validate(raw)
    eff = _merge(DEFAULTS, {k: v for k, v in raw.items() if k not in ('thresholds', 'paths', 'roles')})
    eff['paths'] = {kind: list(raw.get('paths', {}).get(kind, [])) for kind in KINDS}
    # Extra protected paths add to the defaults (CI, code owners): a policy cannot drop them.
    eff['protected'] = sorted(set(DEFAULTS['protected']) | set(raw.get('protected', [])))
    eff['default_paths'] = copy.deepcopy(DEFAULTS['paths'])
    eff['roles'] = copy.deepcopy(DEFAULTS['roles'])
    for role, globs in raw.get('roles', {}).items():
        eff['roles'][role] = sorted(set(eff['roles'].get(role, [])) | set(globs))
    eff['thresholds'] = copy.deepcopy(DEFAULTS['thresholds'])
    for metric, spec in raw.get('thresholds', {}).items():
        eff['thresholds'][metric] = merge_spec(eff['thresholds'].get(metric), spec)
    return eff


def merge_spec(base: dict | None, override: dict) -> dict:
    """Merge a threshold spec. A spec without any `limit` tracks every value (metric budgets)."""
    merged = _merge(base or {}, {k: v for k, v in override.items() if k != 'limit'})
    if 'limit' in (base or {}) or 'limit' in override:
        merged['limit'] = {**(base or {}).get('limit', {}), **override.get('limit', {})}
    return merged


def _fail(message: str) -> None:
    raise GuardError(message)


def validate(raw: dict) -> None:
    if not isinstance(raw, dict):
        _fail('the policy file must be a JSON object')
    unknown = set(raw) - TOP_KEYS
    if unknown:
        _fail(f'unknown policy fields: {", ".join(sorted(unknown))}')
    if raw.get('version', 2) != 2:
        _fail(f"unsupported policy version {raw.get('version')}")
    for kind in raw.get('paths', {}):
        if kind not in KINDS:
            _fail(f'paths: unknown code kind {kind} (known: {", ".join(KINDS)})')
    languages = raw.get('languages', {})
    if not isinstance(languages, dict) or not all(
            isinstance(k, str) and re.fullmatch(r'\.[A-Za-z0-9_+-]+', k) and isinstance(v, str) and v
            for k, v in languages.items()):
        _fail('languages maps file extensions to language names, e.g. {".gleam": "gleam"}')
    for metric, spec in raw.get('thresholds', {}).items():
        if spec.get('mode', 'ratchet') not in MODE_ORDER:
            _fail(f'thresholds.{metric}.mode must be one of {"/".join(MODE_ORDER)}')
    names = set()
    for guard in raw.get('guards', []):
        _validate_guard(guard, names)


def _validate_guard(guard: dict, names: set) -> None:
    name = guard.get('name')
    if not name or not re.fullmatch(r'[a-z0-9][a-z0-9_.-]*', str(name)):
        _fail(f'guard names use lowercase letters, digits and -_. : {name!r}')
    if name in names:
        _fail(f'duplicate guard name: {name}')
    names.add(name)
    unknown = set(guard) - GUARD_KEYS
    if unknown:
        _fail(f'guard {name}: unknown fields {", ".join(sorted(unknown))}')
    minimum = guard.get('min')
    if minimum is not None and not (isinstance(minimum, dict) and all(
            isinstance(v, (int, float)) and not isinstance(v, bool) for v in minimum.values())):
        _fail(f'guard {name}: min maps code kinds to numbers, e.g. {{"logic": 80}}')
    score = guard.get('min_score')
    if score is not None and (not isinstance(score, (int, float)) or isinstance(score, bool)):
        _fail(f'guard {name}: min_score must be a number')
    builtin = guard.get('builtin')
    if builtin:
        if builtin not in BUILTINS:
            _fail(f'guard {name}: builtin {builtin} does not exist (known: {", ".join(BUILTINS)})')
        if builtin in RUN_REQUIRED and not guard.get('run'):
            _fail(f'guard {name} ({builtin}) needs a run command')
        if builtin in REPORT_BUILTINS and not (guard.get('run') or guard.get('input')):
            _fail(f'guard {name} ({builtin}) needs input (a report path) or run')
        if builtin not in RUN_REQUIRED + REPORT_BUILTINS and guard.get('run'):
            _fail(f'built-in guard {name} ({builtin}) takes no run command')
    elif not guard.get('run'):
        _fail(f'guard {name} needs run or builtin')
    elif guard.get('parse', 'findings') not in PARSERS:
        _fail(f'guard {name}: parse {guard.get("parse")} does not exist (known: {", ".join(PARSERS)})')
    if guard.get('tier', 'standard') not in TIERS:
        _fail(f'guard {name}: tier must be one of {"/".join(TIERS)}')
    if guard.get('mode', 'ratchet') not in MODE_ORDER:
        _fail(f'guard {name}: mode must be one of {"/".join(MODE_ORDER)}')
    for rule, mode in guard.get('modes', {}).items():
        if mode not in MODE_ORDER:
            _fail(f'guard {name}: modes.{rule} must be one of {"/".join(MODE_ORDER)}')


def load(root: str, text: str | None = None) -> tuple[dict, dict]:
    """Return (raw policy, effective policy). A missing policy is an error: no rules is not a pass."""
    if text is None:
        path = os.path.join(root, POLICY_PATH)
        if not os.path.exists(path):
            _fail(f'no policy file {POLICY_PATH}; run guard.py init --write first')
        with open(path, encoding='utf-8') as fh:
            text = fh.read()
    try:
        raw = json.loads(text)
    except json.JSONDecodeError as err:
        raise GuardError(f'{POLICY_PATH} is not valid JSON: {err}') from err
    return raw, effective(raw)


# ─── classification ──────────────────────────────────────────────────────────
def language(path: str, policy: dict | None = None) -> str | None:
    ext = os.path.splitext(path)[1].lower()
    extra = (policy or {}).get('languages') or {}
    return extra.get(ext) or LANGUAGES.get(ext)


def is_code(path: str, policy: dict | None = None) -> bool:
    return language(path, policy) is not None


def has_generated_header(text: str | None) -> bool:
    if not text:
        return False
    for line in text.splitlines()[:5]:
        if COMMENT_START.match(line) and GENERATED_HEADER.search(line):
            return True
    return False


def kind_by_path(policy: dict, path: str) -> str:
    for table in (policy['paths'], policy['default_paths']):
        for kind in KINDS:
            if any_match(path, table.get(kind)):
                return kind
    return 'logic'


def classify(policy: dict, path: str, head: str | None = None) -> str:
    """Code kind. Path rules first; a generated-file header only reclassifies otherwise-logic code."""
    kind = kind_by_path(policy, path)
    if kind == 'logic' and has_generated_header(head):
        return 'generated'
    return kind


def excluded(policy: dict, path: str) -> bool:
    """Excluded by the policy, or part of the guard runner itself (protected, not project code)."""
    return any_match(path, policy['exclude']) or glob_match(path, policy['runner'].rstrip('/') + '/**')


def roles_of(policy: dict, path: str) -> set[str]:
    roles = {role for role, globs in policy['roles'].items() if any_match(path, globs)}
    if any_match(path, policy['paths'].get('migration')) or any_match(path, policy['default_paths']['migration']):
        roles.add('migration')
    pattern = policy.get('security_pattern')
    if pattern and re.search(pattern, path, re.IGNORECASE):
        roles.add('security')
    if glob_match(path, policy['runner'].rstrip('/') + '/**'):
        roles.add('guard')
    return roles


def threshold_spec(policy: dict, metric: str, guard: dict | None = None) -> dict | None:
    spec = policy['thresholds'].get(metric)
    override = (guard or {}).get('thresholds', {}).get(metric)
    return merge_spec(spec, override) if override else spec


def limit_for(spec: dict, kind: str, lang: str | None):
    """Look up the threshold by "kind.language", then "kind", then "*". None = not checked."""
    limits = spec.get('limit', {})
    for key in (f'{kind}.{lang}' if lang else None, kind, '*'):
        if key and key in limits:
            return limits[key]
    return None


